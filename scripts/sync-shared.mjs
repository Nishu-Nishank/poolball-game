// Copies the tournament domain code (parser, validation, scoring) from src/ into the Edge Functions
// folder, because Supabase deploys only files under supabase/functions/. src/ stays the single
// source of truth; `npm run build` and `npm run functions:deploy` run this first so the copies stay current.
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';

export const SHARED_FILES = [
  'types/tournament.ts',
  'services/errors.ts',
  'services/workbookMapping.ts',
  'services/excelParser.ts',
  'services/importValidation.ts',
  'services/datasetCodec.ts',
  'utils/pointsCalculator.ts',
];
export const TARGET = 'supabase/functions/_shared/tournament';
export const HEADER = '// GENERATED by scripts/sync-shared.mjs from src/ - do not edit here; run `npm run sync:shared`.\n';

/**
 * SheetJS is vendored because Supabase's function bundler cannot download from cdn.sheetjs.com
 * (the package is not on npm beyond 0.18.5). Copying from node_modules keeps the function on the
 * same version as the dashboard.
 */
const VENDOR = { 'node_modules/xlsx/xlsx.mjs': 'supabase/functions/_shared/vendor/xlsx.mjs' };

if (process.argv[1]?.endsWith('sync-shared.mjs')) {
  for (const file of SHARED_FILES) {
    const target = join(TARGET, file);
    mkdirSync(dirname(target), { recursive: true });
    writeFileSync(target, HEADER + readFileSync(join('src', file), 'utf8'));
  }
  for (const [from, to] of Object.entries(VENDOR)) {
    mkdirSync(dirname(to), { recursive: true });
    writeFileSync(to, readFileSync(from));
  }
  console.log(`Synced ${SHARED_FILES.length} files to ${TARGET} and vendored ${Object.keys(VENDOR).length} dependency`);
}
